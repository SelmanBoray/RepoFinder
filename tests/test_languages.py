"""End-to-end tests: build_index on small JS / Go / Rust / Java repositories, store round trip, search."""

from __future__ import annotations

from pathlib import Path
from typing import Callable

from repofinder.ingest import build_index
from repofinder.models import RepoIndex, Symbol
from repofinder.search import SearchIndex
from repofinder.store import Store

MakeRepo = Callable[[dict], Path]


def _build(root: Path) -> RepoIndex:
    return build_index(root, "demo", str(root))


def _paths(index: RepoIndex) -> set[str]:
    return {f.path for f in index.files}


def _sym(index: RepoIndex, qualname: str) -> Symbol:
    matches = [s for s in index.symbols if s.qualname == qualname]
    assert matches, f"{qualname} not found in {sorted(s.qualname for s in index.symbols)}"
    return matches[0]


def _edges(index: RepoIndex, src: str):
    return [e for e in index.imports if e.src_path == src]


def _first(index: RepoIndex, query: str, qualname: str) -> None:
    hits = SearchIndex(index).search(query)
    assert hits, f"no hits for {query!r}"
    assert hits[0].symbol_id == f"{_sym(index, qualname).path}::{qualname}", (query, hits[0])


