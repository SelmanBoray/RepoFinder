def test_store_round_trip_go(make_repo: MakeRepo, tmp_path: Path) -> None:
    index = _build(make_repo(GO_FILES))
    with Store(tmp_path / "index.db") as store:
        store.save_index(index)
        loaded = store.load_index()
    assert loaded == index
    assert {s.qualname for s in loaded.symbols} >= {"Store", "Store.Get"}
    assert [e.dst_path for e in loaded.imports] == [e.dst_path for e in index.imports]
    assert any(e.dst_path and e.dst_path.startswith("store/") for e in loaded.imports)


