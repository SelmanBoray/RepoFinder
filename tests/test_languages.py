# per-language end-to-end
# --------------------------------------------------------------------------- #


def test_javascript_repo(make_repo: MakeRepo) -> None:
    index = _build(make_repo(JS_FILES))
    paths = _paths(index)
    assert {"src/app.js", "src/util.js", "src/c.ts"} <= paths
    assert "src/c.js" not in paths  # compiled sibling of c.ts
    langs = {f.path: f.language for f in index.files}
    assert langs["src/app.js"] == "javascript"
    assert langs["src/c.ts"] == "typescript"
    assert _sym(index, "App").kind == "class"
    assert _sym(index, "App.method").parent == "App"
    assert _sym(index, "helper").path == "src/util.js"
    assert "src/util.js" in {e.dst_path for e in _edges(index, "src/app.js")}


def test_go_repo(make_repo: MakeRepo) -> None:
    index = _build(make_repo(GO_FILES))
    paths = _paths(index)
    assert {"main.go", "store/store.go"} <= paths
    assert "api.pb.go" not in paths
    assert {f.language for f in index.files if f.path.endswith(".go")} == {"go"}
    assert _sym(index, "Store").kind == "class"
    get = _sym(index, "Store.Get")
    assert get.kind == "method" and get.parent == "Store"
    edges = _edges(index, "main.go")
    store_edge = next(e for e in edges if e.dst_module.endswith("/store"))
    assert store_edge.dst_path is not None
    assert store_edge.dst_path.startswith("store/")
    assert not store_edge.dst_path.endswith("_test.go")
    fmt_edge = next(e for e in edges if e.dst_module == "fmt")
    assert fmt_edge.dst_path is None


def test_rust_repo(make_repo: MakeRepo) -> None:
    index = _build(make_repo(RUST_FILES))
    paths = _paths(index)
    assert {"src/lib.rs", "src/util.rs"} <= paths
    assert not any(p.startswith("target/") for p in paths)
    assert {f.language for f in index.files if f.path.endswith(".rs")} == {"rust"}
    new = _sym(index, "Config.new")
    assert new.kind == "method" and new.parent == "Config"
    assert "src/util.rs" in {e.dst_path for e in _edges(index, "src/lib.rs")}


def test_java_repo(make_repo: MakeRepo) -> None:
    index = _build(make_repo(JAVA_FILES))
    paths = _paths(index)
    assert {"src/main/java/com/demo/App.java", "src/main/java/com/demo/util/Helper.java"} <= paths
    assert not any(p.startswith("target/") for p in paths)
    assert {f.language for f in index.files if f.path.endswith(".java")} == {"java"}
    assert _sym(index, "App").path.endswith("App.java")
    assert _sym(index, "Helper").path.endswith("Helper.java")
    dsts = {e.dst_path for e in _edges(index, "src/main/java/com/demo/App.java")}
    assert "src/main/java/com/demo/util/Helper.java" in dsts


