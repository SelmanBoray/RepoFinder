JS_FILES = {
    "src/app.js": "const util = require('./util');\n\nclass App {\n  method() {\n    return util.helper();\n  }\n}\n\nmodule.exports = App;\n",
    "src/util.js": "exports.helper = function () {};\n",
    "src/c.ts": "export const c = 1;\n",
    "src/c.js": "exports.c = 1;\n",
}
GO_FILES = {
    "go.mod": "module example.com/demo\n\ngo 1.21\n",
    "main.go": 'package main\n\nimport (\n\t"fmt"\n\t"example.com/demo/store"\n)\n\nfunc main() {\n\tfmt.Println(store.Store{})\n}\n',
    "store/store.go": "package store\n\ntype Store struct{}\n\nfunc (s *Store) Get(k string) string {\n\treturn k\n}\n",
    "store/store_test.go": "package store\n\nimport \"testing\"\n\nfunc TestGet(t *testing.T) {}\n",
    "api.pb.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage main\n\ntype Msg struct{}\n",
}
RUST_FILES = {
    "Cargo.toml": '[package]\nname = "demo"\n',
    "src/lib.rs": "mod util;\n\npub struct Config;\n\nimpl Config {\n    pub fn new() -> Self {\n        Config\n    }\n}\n",
    "src/util.rs": "pub fn tool() {}\n",
    "target/debug/gen.rs": "pub fn generated() {}\n",
}
JAVA_FILES = {
    "src/main/java/com/demo/App.java": "package com.demo;\n\nimport com.demo.util.Helper;\n\npublic class App {\n    public void run() {\n        Helper.format(\"x\");\n    }\n}\n",
    "src/main/java/com/demo/util/Helper.java": "package com.demo.util;\n\npublic class Helper {\n    public static String format(String s) {\n        return s;\n    }\n}\n",
    "pom.xml": "<project></project>\n",
    "target/classes/X.java": "package x;\npublic class X {}\n",
}


