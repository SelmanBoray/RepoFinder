def test_search_javascript(make_repo: MakeRepo) -> None:
    _first(_build(make_repo(JS_FILES)), "helper", "helper")


def test_search_go(make_repo: MakeRepo) -> None:
    _first(_build(make_repo(GO_FILES)), "where is Store.Get", "Store.Get")


def test_search_rust(make_repo: MakeRepo) -> None:
    _first(_build(make_repo(RUST_FILES)), "Config::new", "Config.new")


def test_search_java(make_repo: MakeRepo) -> None:
    index = _build(make_repo(JAVA_FILES))
    _first(index, "Helper.format", "Helper.format")
